// NT-12: with nobody selected the centre shows the scene's prep; the side history lists what
// happened (a player's request, a state change, a roll). Screenshots: ./e2e-output/center-*.png
import { chromium } from 'playwright'
const BASE = 'http://localhost:5173/'
const out = process.env.E2E_OUT ?? '/out'
const browser = await chromium.launch()
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a)
const fail = msg => { console.error('FAIL:', msg); process.exit(1) }
async function seat(name, viewport) {
  const page = await (await browser.newContext({ viewport })).newPage()
  page.on('pageerror', e => log(`[${name} pageerror]`, e.message.slice(0, 200)))
  await page.goto(BASE)
  await page.getByRole('button', { name: new RegExp(`^${name}`) }).first().click()
  await page.waitForURL(/#\/mesa\//)
  return page
}
const master = await seat('Mestre', { width: 1440, height: 900 })
const start = master.getByRole('button', { name: 'Começar a sessão' })
await Promise.race([start.waitFor({ timeout: 15000 }), master.locator('.scene-banner').waitFor({ timeout: 15000 })]).catch(() => {})
if (await start.isVisible()) await start.click()
const back = master.locator('.back-to-center')
if (await back.isVisible().catch(() => false)) await back.click()
const center = master.locator('.control-center')
await center.waitFor({ timeout: 15000 })
await master.waitForTimeout(1200)
log('cards:', (await center.locator('.cc-card h3').allTextContents()).join(' | '))
if (!(await center.locator('.cc-npc').count())) log('note: no NPC cards in this scene')
await master.screenshot({ path: `${out}/center-1.png`, fullPage: true })

// Something happens: Lyra asks, the master hurts her, then the history shows it.
const lyra = await seat('Lyra', { width: 390, height: 844 })
await lyra.locator('.paper-stats .medallion').first().waitFor({ timeout: 15000 })
await lyra.locator('.paper-stats .medallion').first().click()
await lyra.getByLabel('Intenção').fill('Segurar o portão')
await lyra.getByRole('button', { name: 'Sugerir ao mestre' }).click()
await master.locator('.cc-person', { hasText: 'Lyra' }).locator('.flag.ask').waitFor({ timeout: 10000 })
await master.locator('.cc-person', { hasText: 'Lyra' }).click()
await master.locator('.inspector').waitFor()
await master.locator('.inspector').getByRole('button', { name: /menos 1/ }).first().click()
await master.waitForTimeout(800)
await master.locator('.inspector').getByRole('button', { name: 'Dispensar' }).click()
await master.getByRole('tab', { name: 'Histórico' }).click()
const hist = master.locator('.history-list')
await hist.locator('li', { hasText: 'pediu para rolar com Lyra' }).waitFor({ timeout: 10000 })
await hist.locator('li', { hasText: /Lyra: Vida/ }).first().waitFor({ timeout: 10000 })
log('history top:', (await hist.locator('li').allTextContents()).slice(0, 4).map(t => t.replace(/\s+/g, ' ').trim()).join(' || '))
await master.locator('.back-to-center').click()
await center.waitFor()
await master.screenshot({ path: `${out}/center-2-history.png` })
// Put Lyra's vitality back, then use the action dialogs.
await master.locator('.cc-person', { hasText: 'Lyra' }).click()
const insp = master.locator('.inspector')
await insp.getByRole('button', { name: /mais 1/ }).first().click()
await master.waitForTimeout(600)
await insp.getByRole('button', { name: '+ condição' }).click()
const cond = master.getByRole('dialog', { name: 'Condições de Lyra' })
await cond.getByRole('button', { name: 'Envenenado' }).click()
await cond.getByRole('button', { name: 'Envenenado', pressed: true }).waitFor({ timeout: 10000 })
await master.screenshot({ path: `${out}/center-3-conditions.png` })
await cond.getByRole('button', { name: 'Pronto' }).click()
await insp.getByRole('button', { name: /Envenenado ×/ }).waitFor()
await insp.getByRole('button', { name: /Envenenado ×/ }).click()
await insp.getByRole('button', { name: /Envenenado ×/ }).waitFor({ state: 'detached', timeout: 10000 })
log('condition dialog: on, chip, off')
await insp.getByRole('button', { name: '+ Dar item' }).click()
const give = master.getByRole('dialog', { name: 'Dar um item' })
await give.getByLabel('Item').fill('Poção de cura')
await give.getByRole('button', { name: 'Mais' }).click()
await give.getByLabel('Nota (opcional)').fill('cura 1d4')
await master.screenshot({ path: `${out}/center-4-item.png` })
await give.getByRole('button', { name: 'Dar', exact: true }).click()
const potion = insp.locator('.item', { hasText: 'Poção de cura' })
await potion.waitFor({ timeout: 10000 })
log('item given:', (await potion.textContent()).replace(/\s+/g, ' ').trim())
for (let i = 0; i < 2; i++) { await potion.getByRole('button', { name: /Gastar/ }).click(); await master.waitForTimeout(500) }
await potion.waitFor({ state: 'detached', timeout: 10000 })
await insp.locator('.medallion').first().click()
await insp.getByRole('button', { name: 'mais opções' }).click()
const opts = master.getByRole('dialog', { name: 'Opções da rolagem' })
await opts.waitFor()
await master.waitForTimeout(500)
await master.screenshot({ path: `${out}/center-5-roll-options.png` })
await opts.getByRole('button', { name: 'Pronto' }).click()
await opts.waitFor({ state: 'detached' })
log('roll options dialog ok')
await browser.close()
log('OK')
